@st.cache_data
def load_all_tasks():
    try:
        tasks = load_tasks(str(DATASET_PATH))
        return {task["task_id"]: task for task in tasks}
    except Exception:
        return {}


def load_csv_safe(path: str) -> pd.DataFrame:
    if not os.path.exists(path):
        return pd.DataFrame()
    try:
        return pd.read_csv(path)
    except Exception:
        return pd.DataFrame()


def load_json_safe(path: str):
    if not os.path.exists(path):
        return {}
    try:
        with open(path, "r", encoding="utf-8") as handle:
            return json.load(handle)
    except Exception:
        return {}


def contract_summary_table(task_contract: dict) -> pd.DataFrame:
    rows = []
    for class_info in task_contract.get("classes", []):
        class_name = class_info.get("name", "")
        class_kind = class_info.get("kind", "")
        inherits = ", ".join(class_info.get("inherits", [])) or "-"
        rows.append(
            {
                "class": class_name,
                "kind": class_kind,
                "inherits": inherits,
                "required_methods": ", ".join(
                    [
                        method["name"]
                        for method in task_contract.get("methods", [])
                        if method.get("class") == class_name
                    ]
                )
                or "-",
            }
        )
    return pd.DataFrame(rows)


def load_experiment_generation(model_id: str, task_id: str, condition: str, run_num: int):
    run_dir = EXPERIMENTS_DIR / model_id / task_id / f"{condition}_run_{run_num:02d}"
    raw_path = run_dir / "raw_code.txt"
    eval_path = run_dir / "evaluation.json"

    if not raw_path.exists():
        return None, None, None

    with open(raw_path, "r", encoding="utf-8", errors="replace") as handle:
        raw_code = handle.read()

    eval_data = load_json_safe(str(eval_path))
    return run_dir, raw_code, eval_data


def page_research_dashboard():
    st.title("Research Dashboard")
    st.markdown("Verified experimental results and figures from the completed CAPS study.")

    overall_df = load_csv_safe(str(ANALYSIS_DIR / "overall_summary.csv"))
    model_df = load_csv_safe(str(ANALYSIS_DIR / "model_summary.csv"))
    pattern_df = load_csv_safe(str(ANALYSIS_DIR / "pattern_summary.csv"))
    task_df = load_csv_safe(str(ANALYSIS_DIR / "task_summary.csv"))
    stats_df = load_csv_safe(str(ANALYSIS_DIR / "statistical_tests.csv"))

    if overall_df.empty:
        st.warning("No verified research summary is available yet. The results/analysis folder is missing or empty.")
        return

    baseline_row = overall_df[overall_df["condition"] == "baseline"].iloc[0]
    caps_row = overall_df[overall_df["condition"] == "caps"].iloc[0]

    col1, col2, col3, col4, col5 = st.columns(5)
    col1.metric(
        "Overall Interface Conformance",
        f"{float(caps_row['interface_conformance_mean']) * 100:.1f}%",
        f"vs baseline {float(baseline_row['interface_conformance_mean']) * 100:.1f}%",
    )
    col2.metric(
        "Violation Count",
        f"{float(caps_row['violation_count_mean']):.2f}",
        f"baseline {float(baseline_row['violation_count_mean']):.2f}",
    )
    col3.metric(
        "Functional Score",
        f"{float(caps_row['functional_score_mean']) * 100:.1f}%",
        f"baseline {float(baseline_row['functional_score_mean']) * 100:.1f}%",
    )
    col4.metric(
        "Functional Valid Rate",
        f"{float(caps_row['functional_valid_rate']) * 100:.1f}%",
        f"baseline {float(baseline_row['functional_valid_rate']) * 100:.1f}%",
    )
    col5.metric(
        "AST Validity",
        f"{float(caps_row['ast_valid_rate']) * 100:.1f}%",
        f"baseline {float(baseline_row['ast_valid_rate']) * 100:.1f}%",
    )

    st.markdown("---")
    st.subheader("Claude vs DeepSeek comparison")
    if model_df.empty:
        st.info("No model-level summary available.")
    else:
        st.dataframe(model_df, use_container_width=True)

    st.subheader("Pattern-level results")
    if pattern_df.empty:
        st.info("No pattern-level summary available.")
    else:
        st.dataframe(pattern_df, use_container_width=True)

    st.subheader("Task-level results")
    if task_df.empty:
        st.info("No task-level summary available.")
    else:
        st.dataframe(task_df, use_container_width=True)

    st.markdown("---")
    st.subheader("Saved figures")
    figure_paths = sorted(ANALYSIS_FIGURES_DIR.glob("*.png"))
    if not figure_paths:
        st.info("No research figures are currently available in the analysis directory.")
    else:
        columns = st.columns(min(3, len(figure_paths)))
        for idx, fig_path in enumerate(figure_paths):
            with columns[idx % len(columns)]:
                st.image(str(fig_path), caption=fig_path.name, use_container_width=True)

    if not stats_df.empty:
        st.subheader("Statistical verification")
        st.dataframe(stats_df, use_container_width=True)


def page_caps_analysis():
    st.title("CAPS Analysis")
    st.markdown("Inspect a previously recorded generation from the formal experiment data store.")

    model_id = st.selectbox("Model", MODELS)
    task_id = st.selectbox("Task", TASKS)
    condition = st.selectbox("Condition", CONDITIONS)
    run_num = st.selectbox("Run", RUNS)

    run_dir, raw_code, eval_data = load_experiment_generation(model_id, task_id, condition, run_num)
    if run_dir is None:
        st.warning(f"No stored experiment was found for {model_id}/{task_id}/{condition}_run_{run_num:02d}.")
        return

    structural = eval_data.get("structural", {})
    functional = eval_data.get("functional", {})

    st.subheader(f"Stored run: {run_dir.name}")
    col1, col2, col3, col4, col5 = st.columns(5)
    col1.metric("AST validity", "VALID" if structural.get("ast_valid") else "INVALID")
    col2.metric("Interface conformance", f"{float(structural.get('interface_conformance', 0.0)) * 100:.1f}%")
    col3.metric("Violation count", f"{structural.get('violation_count', 0)}")
    col4.metric("Functional validity", "PASS" if functional.get("functional_valid") else "FAIL")
    col5.metric("Functional score", f"{float(functional.get('functional_score', 0.0)):.2f}")

    violations = structural.get("violations", [])
    if violations:
        st.warning(f"**Structural violations ({len(violations)})**")
        for violation in violations:
            st.markdown(f"- {violation}")
    else:
        st.success("No structural violations reported for this run.")

    with st.expander("Generated source code"):
        st.code(raw_code, language="python")

    with st.expander("Structural evaluation details"):
        st.json(structural)

    with st.expander("Functional evaluation details"):
        st.json(functional)


def page_task_contracts():
    st.title("Structural Contract")
    st.markdown("Display the actual contract for the selected benchmark task from the frozen dataset.")

    tasks = load_all_tasks()
    if not tasks:
        st.warning("The dataset task contracts are unavailable.")
        return

    task_id = st.selectbox("Task", list(tasks.keys()))
    task = tasks[task_id]
    contract = task.get("contract", {})

    st.subheader(f"{task_id} — {task.get('pattern', 'N/A')}")
    st.markdown(task.get("description", ""))

    st.markdown("### Required classes")
    st.dataframe(contract_summary_table(contract), use_container_width=True)

    method_rows = []
    for method in contract.get("methods", []):
        params = []
        for parameter in method.get("parameters", []):
            params.append(f"{parameter.get('name')}: {parameter.get('type', 'Any')}")
        method_rows.append(
            {
                "class": method.get("class"),
                "method": method.get("name"),
                "parameters": ", ".join(params) if params else "-",
                "return_type": method.get("return_type", "None"),
                "abstract": method.get("abstract", False),
                "static": method.get("static", False),
            }
        )

    st.markdown("### Required methods")
    st.dataframe(pd.DataFrame(method_rows), use_container_width=True)

    st.markdown("### Raw contract JSON")
    st.json(contract)


def page_caps_repair():
    st.title("CAPS-Repair")
    st.markdown(
        "Repair workflow built around the existing RepairEngine and the stored generation data. "
        "This project does not configure an automatic LLM API, so the repair prompt is generated and the response is pasted back for evaluation."
    )

    model_id = st.selectbox("Model", MODELS, key="repair_model")
    task_id = st.selectbox("Task", TASKS, key="repair_task")
    condition = st.selectbox("Condition", CONDITIONS, key="repair_condition")
    run_num = st.selectbox("Run", RUNS, key="repair_run")

    run_dir, raw_code, eval_data = load_experiment_generation(model_id, task_id, condition, run_num)
    if run_dir is None:
        st.warning(f"No experiment exists for {model_id}/{task_id}/{condition}_run_{run_num:02d}.")
        return

    structural = eval_data.get("structural", {})
    functional = eval_data.get("functional", {})

    pre_conformance = float(structural.get("interface_conformance", 0.0)) * 100
    before_violation_count = int(structural.get("violation_count", 0))
    pre_valid = bool(functional.get("functional_valid", False))
    pre_score = float(functional.get("functional_score", 0.0))

    col1, col2, col3, col4, col5 = st.columns(5)
    col1.metric("AST validity", "VALID" if structural.get("ast_valid") else "INVALID")
    col2.metric("Conformance", f"{pre_conformance:.1f}%")
    col3.metric("Violations", str(before_violation_count))
    col4.metric("Functional valid", "PASS" if pre_valid else "FAIL")
    col5.metric("Functional score", f"{pre_score:.2f}")

    with st.expander("Before source code"):
        st.code(raw_code, language="python")

    st.subheader("Repair prompt")
    engine = RepairEngine()
    violations = structural.get("violations", [])
    prompt = engine.construct_repair_prompt(task_id, raw_code, violations)
    st.code(prompt, language="text")

    repaired_code = st.text_area(
        "Paste the LLM-repaired Python source here",
        height=300,
        placeholder="Paste only the repaired Python source code returned by the model.",
    )

    if st.button("Evaluate repair", type="primary"):
        if not repaired_code.strip():
            st.warning("Paste a repaired code response before evaluating it.")
        else:
            repaired_eval = engine.evaluate_code(task_id, repaired_code, run_functional=True)
            repaired_struct = repaired_eval.get("structural", {})
            repaired_func = repaired_eval.get("functional", {})

            st.subheader("Repair iteration results")
            iteration_rows = [
                {
                    "Iteration": 0,
                    "Code": "Original generation",
                    "Conformance": f"{pre_conformance:.1f}%",
                    "Violations": before_violation_count,
                    "Functional valid": "PASS" if pre_valid else "FAIL",
                },
                {
                    "Iteration": 1,
                    "Code": "Pasted repair",
                    "Conformance": f"{float(repaired_struct.get('interface_conformance', 0.0)) * 100:.1f}%",
                    "Violations": int(repaired_struct.get("violation_count", 0)),
                    "Functional valid": "PASS" if repaired_func.get("functional_valid", False) else "FAIL",
                },
            ]
            st.dataframe(pd.DataFrame(iteration_rows), use_container_width=True)

            with st.expander("Iteration 1 repaired code"):
                st.code(repaired_code, language="python")

            st.subheader("Before vs After")
            before_after_df = pd.DataFrame(
                [
                    {
                        "Metric": "Interface Conformance",
                        "Before": f"{pre_conformance:.1f}%",
                        "After": f"{float(repaired_struct.get('interface_conformance', 0.0)) * 100:.1f}%",
                    },
                    {
                        "Metric": "Violation Count",
                        "Before": before_violation_count,
                        "After": int(repaired_struct.get("violation_count", 0)),
                    },
                    {
                        "Metric": "Functional Validity",
                        "Before": "PASS" if pre_valid else "FAIL",
                        "After": "PASS" if repaired_func.get("functional_valid", False) else "FAIL",
                    },
                    {
                        "Metric": "Functional Score",
                        "Before": f"{pre_score:.2f}",
                        "After": f"{float(repaired_func.get('functional_score', 0.0)):.2f}",
                    },
                ]
            )
            st.dataframe(before_after_df, use_container_width=True)

            post_conformance = float(repaired_struct.get("interface_conformance", 0.0))
            post_violation_count = int(repaired_struct.get("violation_count", 0))
            post_valid = bool(repaired_func.get("functional_valid", False))

            if repaired_struct.get("ast_valid") and post_conformance >= 1.0 and post_violation_count == 0 and post_valid:
                st.success("FINAL REPAIR STATUS: FULL REPAIR")
            elif post_conformance > float(structural.get("interface_conformance", 0.0)) or post_violation_count < before_violation_count:
                st.warning("FINAL REPAIR STATUS: PARTIAL REPAIR")
            else:
                st.error("FINAL REPAIR STATUS: REPAIR FAILED")


def page_repair_history():
    st.title("Repair History")
    st.markdown("Display the saved repair experiments and comparison metrics from results/repair_experiments/.")

    repair_summary_path = REPAIR_DIR / "repair_summary.csv"
    if not repair_summary_path.exists():
        st.warning("No repair summary CSV is available yet. Repair results have not been recorded in results/repair_experiments/.")
        return

    summary_df = load_csv_safe(str(repair_summary_path))
    if summary_df.empty:
        st.warning("The repair summary file exists but no rows were loaded.")
        return

    st.subheader("Repair summary")
    st.dataframe(summary_df, use_container_width=True)

    repair_figures_dir = REPAIR_DIR / "figures"
    figure_paths = sorted(repair_figures_dir.glob("*.png")) if repair_figures_dir.exists() else []
    if figure_paths:
        st.subheader("Repair figures")
        cols = st.columns(min(3, len(figure_paths)))
        for idx, fig_path in enumerate(figure_paths):
            with cols[idx % len(cols)]:
                st.image(str(fig_path), caption=fig_path.name, use_container_width=True)


def main():
    st.set_page_config(
        page_title="CAPS Research Studio",
        page_icon="⚡",
        layout="wide",
        initial_sidebar_state="expanded",
    )

    st.sidebar.title("CAPS Studio")
    st.sidebar.markdown("---")
    page = st.sidebar.radio(
        "Sections",
        [
            "Research Dashboard",
            "CAPS Analysis",
            "Structural Contract",
            "CAPS-Repair",
            "Repair History",
        ],
    )

    st.sidebar.markdown("---")
    required_paths = {
        "dataset/test_tasks.json": DATASET_PATH,
        "results/analysis/": ANALYSIS_DIR,
        "results/experiments/": EXPERIMENTS_DIR,
        "results/repair_experiments/": REPAIR_DIR,
    }
    missing_paths = [label for label, path in required_paths.items() if not path.exists()]
    if missing_paths:
        st.sidebar.warning("Missing data: " + ", ".join(missing_paths))
    else:
        st.sidebar.success("Verified project artifacts detected.")

    if page == "Research Dashboard":
        page_research_dashboard()
    elif page == "CAPS Analysis":
        page_caps_analysis()
    elif page == "Structural Contract":
        page_task_contracts()
    elif page == "CAPS-Repair":
        page_caps_repair()
    elif page == "Repair History":
        page_repair_history()


if __name__ == "__main__":
    main()
