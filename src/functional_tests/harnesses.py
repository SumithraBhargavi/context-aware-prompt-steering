KNOWN_TASK_IDS = list(_TASK_BODIES.keys())


def get_test_harness(task_id: str) -> str:
    """
    Return the complete functional test harness script for task_id.

    The returned string is designed to be APPENDED to the normalized
    generated code and executed as a single Python script in a subprocess.

    Args:
        task_id: One of the 10 known task identifiers.

    Returns:
        str: Complete harness script string.

    Raises:
        KeyError: If task_id is not recognized.
    """
    if task_id not in _TASK_BODIES:
        raise KeyError(
            f"No harness registered for task '{task_id}'. "
            f"Known tasks: {KNOWN_TASK_IDS}"
        )

    return (
        _HARNESS_HEADER
        + _TASK_BODIES[task_id]
        + _HARNESS_FOOTER
    )
