# adapter_02  –  Legacy Temperature Sensor Adapter
# Task: TemperatureAdapter wraps LegacyTemperatureSensor and
#       converts Fahrenheit to Celsius.
#       Conversion: C = (F - 32) * 5 / 9
# ------------------------------------------------------------

_ADAPTER_02_BODY = '''
def _test_legacy_sensor_instantiate():
    LegacyTemperatureSensor()
    return True

def _test_legacy_sensor_returns_float():
    s = LegacyTemperatureSensor()
    result = s.get_fahrenheit()
    return isinstance(result, (int, float))

def _test_adapter_instantiate():
    TemperatureAdapter(LegacyTemperatureSensor())
    return True

def _test_adapter_returns_float():
    adapter = TemperatureAdapter(LegacyTemperatureSensor())
    result = adapter.get_temperature()
    return isinstance(result, (int, float))

def _test_adapter_is_temperature_sensor():
    adapter = TemperatureAdapter(LegacyTemperatureSensor())
    return isinstance(adapter, TemperatureSensor)

def _test_adapter_converts_correctly():
    """
    Verify that the adapter applies the Fahrenheit-to-Celsius conversion:
        C = (F - 32) * 5 / 9
    We retrieve F from the legacy sensor directly and compare.
    """
    sensor = LegacyTemperatureSensor()
    fahrenheit = sensor.get_fahrenheit()
    adapter = TemperatureAdapter(sensor)
    celsius = adapter.get_temperature()
    expected = (fahrenheit - 32) * 5 / 9
    return abs(celsius - expected) < 0.001

def _test_adapter_result_differs_from_raw_fahrenheit():
    """
    Unless the Fahrenheit value happens to equal the Celsius value
    (which occurs at exactly -40), the adapter result should differ
    from the raw Fahrenheit value.
    """
    sensor = LegacyTemperatureSensor()
    fahrenheit = sensor.get_fahrenheit()
    if abs(fahrenheit - (-40)) < 0.001:
        # Special case: F == C at -40
        return True
    adapter = TemperatureAdapter(sensor)
    celsius = adapter.get_temperature()
    return abs(celsius - fahrenheit) > 0.001

_run_test("LegacyTemperatureSensor instantiates", _test_legacy_sensor_instantiate)
_run_test("get_fahrenheit() returns a numeric value", _test_legacy_sensor_returns_float)
_run_test("TemperatureAdapter instantiates with sensor", _test_adapter_instantiate)
_run_test("get_temperature() returns a numeric value", _test_adapter_returns_float)
_run_test("TemperatureAdapter is a TemperatureSensor", _test_adapter_is_temperature_sensor)
_run_test("Fahrenheit-to-Celsius conversion is correct", _test_adapter_converts_correctly)
_run_test("Adapter result differs from raw Fahrenheit", _test_adapter_result_differs_from_raw_fahrenheit)
'''


