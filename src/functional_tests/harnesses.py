# ------------------------------------------------------------
# observer_01  –  Weather Monitoring System
# Task: WeatherStation notifies attached PhoneDisplay and
#       WebDisplay when temperature changes; detach works.
# Notes: We subclass the concrete observers inside the harness
#        to track update() calls without inspecting internals.
# ------------------------------------------------------------

_OBSERVER_01_BODY = '''
# Tracking subclasses declared in the harness (not part of generated code)
class _TrackingPhoneDisplay(PhoneDisplay):
    def __init__(self):
        self._received = []
        try:
            super().__init__()
        except Exception:
            pass
    def update(self, temperature: float) -> None:
        self._received.append(temperature)
        try:
            super().update(temperature)
        except Exception:
            pass

class _TrackingWebDisplay(WebDisplay):
    def __init__(self):
        self._received = []
        try:
            super().__init__()
        except Exception:
            pass
    def update(self, temperature: float) -> None:
        self._received.append(temperature)
        try:
            super().update(temperature)
        except Exception:
            pass

def _test_station_instantiate():
    WeatherStation()
    return True

def _test_attach_and_notify():
    ws = WeatherStation()
    pd = _TrackingPhoneDisplay()
    wd = _TrackingWebDisplay()
    ws.attach(pd)
    ws.attach(wd)
    ws.set_temperature(25.0)
    return (
        len(pd._received) >= 1
        and pd._received[-1] == 25.0
        and len(wd._received) >= 1
        and wd._received[-1] == 25.0
    )

def _test_detach_stops_notification():
    ws = WeatherStation()
    pd = _TrackingPhoneDisplay()
    ws.attach(pd)
    ws.set_temperature(10.0)
    ws.detach(pd)
    before = len(pd._received)
    ws.set_temperature(20.0)
    after = len(pd._received)
    return after == before     # no new notification after detach

def _test_multiple_temperatures():
    ws = WeatherStation()
    pd = _TrackingPhoneDisplay()
    ws.attach(pd)
    ws.set_temperature(15.0)
    ws.set_temperature(25.5)
    return (
        len(pd._received) >= 2
        and pd._received[-1] == 25.5
    )

_run_test("WeatherStation instantiates", _test_station_instantiate)
_run_test("attach + set_temperature notifies both observers", _test_attach_and_notify)
_run_test("detach stops notifications", _test_detach_stops_notification)
_run_test("multiple set_temperature calls propagate correctly", _test_multiple_temperatures)
'''

