"""
Functional test harnesses for all 10 CAPS benchmark tasks.

Each harness is a standalone Python script string that:
  1. Is appended to the normalized generated code.
  2. Runs deterministic black-box behavioral tests.
  3. Exits with code 0 if all tests pass.
  4. Exits with code 1 and prints "FAIL: <message>" to stderr for each failure.
  5. Prints "TESTS_PASSED: N" and "TESTS_TOTAL: N" to stdout on completion.

IMPORTANT:
  - These tests verify OBSERVABLE BEHAVIOR required by the task description
    and structural contract only.
  - They do NOT inspect implementation internals beyond what is publicly
    required by the contract.
  - They use test-subclasses (declared inside the harness) to observe
    propagation effects in observer-style patterns.
  - No test alters or repairs the generated code.
"""

# ============================================================
# HARNESS TEMPLATE HEADER
# ============================================================

_HARNESS_HEADER = '''
# ===========================================================
# FUNCTIONAL TEST HARNESS  (research evaluation – read-only)
# Generated by CAPS FunctionalEvaluator. Do NOT edit.
# ===========================================================
import sys as _sys

_failures = []
_tests_total = 0
_tests_passed = 0


def _check(condition: bool, message: str) -> None:
    global _tests_total, _tests_passed
    _tests_total += 1
    if condition:
        _tests_passed += 1
    else:
        _failures.append(message)


def _run_test(label: str, fn):
    """Run fn(); catch any exception and record as failure."""
    global _tests_total, _tests_passed
    _tests_total += 1
    try:
        result = fn()
        if result is False:
            _failures.append(label)
        else:
            _tests_passed += 1
    except Exception as _e:
        _failures.append(f"{label} raised {type(_e).__name__}: {_e}")


'''

_HARNESS_FOOTER = '''
# -----------------------------------------------------------
# REPORT
# -----------------------------------------------------------
print(f"TESTS_TOTAL: {_tests_total}")
print(f"TESTS_PASSED: {_tests_passed}")

if _failures:
    for _f in _failures:
        print(f"FAIL: {_f}", file=_sys.stderr)
    _sys.exit(1)
else:
    print("ALL_TESTS_PASSED")
    _sys.exit(0)
'''


